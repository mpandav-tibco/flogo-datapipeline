// Command dp-build compiles a LEAN, per-app binary for a .datapipeline file by
// linking only the components the app references — the import-driven build model
// used by Flogo flow and the Flogo agents. It derives the import set with the
// core `build` package, generates a minimal main.go, and compiles it. Every
// bundled JDBC driver is pure Go, so these lean binaries build without CGO.
//
//	dp-build -f orders.datapipeline -o bin/orders   # build a lean binary
//	dp-build -f orders.datapipeline -n              # print derived imports only
//
// This is how new apps should ship to production: one small static binary per
// app, not the all-in-one engine that registers every component.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	dpbuild "github.com/mpandav-tibco/flogo-datapipeline/build"
)

func main() {
	appFile := flag.String("f", "", "path to the .datapipeline app file (required)")
	out := flag.String("o", "", "output binary path (required unless -n)")
	dryRun := flag.Bool("n", false, "print the derived imports and exit (no build)")
	flag.Parse()
	if *appFile == "" || (*out == "" && !*dryRun) {
		fmt.Fprintln(os.Stderr, "usage: dp-build -f <app.datapipeline> -o <binary> [-n]")
		os.Exit(2)
	}

	raw, err := os.ReadFile(*appFile)
	check(err)
	imports, cgo, err := dpbuild.ImportsForApp(raw)
	check(err)

	if *dryRun {
		fmt.Printf("cgo=%v\nimports (%d):\n", cgo, len(imports))
		for _, i := range imports {
			fmt.Println("  " + i)
		}
		return
	}
	check(buildBinary(imports, cgo, *out))
	fmt.Printf("built %s (cgo=%v, %d imports)\n", *out, cgo, len(imports))
}

const mainTmpl = `// Code generated by dp-build; DO NOT EDIT.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/signal"
	"syscall"

	"github.com/project-flogo/core/engine"

{{range .}}	_ "{{.}}"
{{end}})

func main() {
	appFile := flag.String("f", "", "path to the .datapipeline file")
	flag.Parse()
	if *appFile == "" {
		fmt.Fprintln(os.Stderr, "usage: -f <pipeline.datapipeline>")
		os.Exit(1)
	}
	raw, err := os.ReadFile(*appFile)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	cfg, err := engine.LoadAppConfig(string(raw), false)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	e, err := engine.New(cfg)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := e.Start(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, syscall.SIGINT, syscall.SIGTERM)
	<-sigCh
	_ = e.Stop()
}
`

// buildBinary renders a minimal main.go that blank-imports exactly the derived
// packages, then compiles it (stripped, trimpath) into out.
func buildBinary(imports []string, cgo bool, out string) error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	genDir := filepath.Join(root, ".dpbuild", "gen")
	if err := os.MkdirAll(genDir, 0o755); err != nil {
		return err
	}
	defer os.RemoveAll(filepath.Join(root, ".dpbuild"))

	f, err := os.Create(filepath.Join(genDir, "main.go"))
	if err != nil {
		return err
	}
	if err := template.Must(template.New("m").Parse(mainTmpl)).Execute(f, imports); err != nil {
		f.Close()
		return err
	}
	f.Close()

	absOut, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	cmd := exec.Command("go", "build", "-trimpath", "-ldflags", "-s -w", "-o", absOut, "./.dpbuild/gen")
	cmd.Dir = root
	cgoEnv := "CGO_ENABLED=0"
	if cgo {
		cgoEnv = "CGO_ENABLED=1"
	}
	cmd.Env = append(os.Environ(), cgoEnv)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	return cmd.Run()
}

// moduleRoot walks up from the working directory to find the module go.mod.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from %s upward", dir)
		}
		dir = parent
	}
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "dp-build:", err)
		os.Exit(1)
	}
}
