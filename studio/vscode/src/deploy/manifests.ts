// Deployment artifact generators for flogo-datapipeline.
// Produces a Dockerfile and a sharded Kubernetes StatefulSet manifest so a
// .datapipeline can be deployed to a Data Plane / any OCI runtime.

import { slug } from '../model/pipeline';

export function dockerfile(pipelineFileName: string): string {
  return `# syntax=docker/dockerfile:1
# Build stage — compile the flogo-datapipeline engine from source.
FROM golang:1.23 AS build
WORKDIR /src
COPY . .
ENV CGO_ENABLED=1
RUN go build -o /out/flogo-datapipeline ./cmd/flogo-datapipeline/

# Runtime stage.
FROM gcr.io/distroless/base-debian12
WORKDIR /app
COPY --from=build /out/flogo-datapipeline /app/flogo-datapipeline
# Copy the pipeline to a fixed in-container path so the source file name (which
# may contain spaces or other special characters) can never break the COPY/ENV
# directives or the ENTRYPOINT argument list. The source name is quoted.
COPY "${pipelineFileName}" /app/pipeline.datapipeline
ENV PIPELINE_FILE=/app/pipeline.datapipeline
ENV PIPELINE_API_ADDR=:9080
EXPOSE 9080
ENTRYPOINT ["/app/flogo-datapipeline", "-f", "/app/pipeline.datapipeline", "-port", "9080"]
`;
}

export function statefulSet(
  pipelineName: string,
  pipelineFileName: string,
  replicas: number,
  image: string,
  envVars: Array<{ name: string; value: string }> = [],
): string {
  const name = slug(pipelineName) || 'data-pipeline';
  const n = Math.max(1, Math.floor(replicas));
  // Secret env references — values are supplied by the Secret below (a template
  // operators fill in), NOT inlined into the manifest.
  const secretEnv = envVars
    .map(
      (e) => `            - name: ${e.name}
              valueFrom:
                secretKeyRef:
                  name: ${name}-secrets
                  key: ${e.name}`,
    )
    .join('\n');
  const secretManifest = envVars.length
    ? `---
apiVersion: v1
kind: Secret
metadata:
  name: ${name}-secrets
type: Opaque
stringData:
${envVars.map((e) => `  ${e.name}: "CHANGE_ME"   # ${e.name}`).join('\n')}
`
    : '';
  return `apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: ${name}
  labels:
    app.kubernetes.io/name: ${name}
    app.kubernetes.io/part-of: flogo-datapipeline
spec:
  serviceName: ${name}
  replicas: ${n}
  podManagementPolicy: Parallel
  selector:
    matchLabels:
      app.kubernetes.io/name: ${name}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: ${name}
    spec:
      containers:
        - name: pipeline
          image: ${image}
          ports:
            - name: api
              containerPort: 9080
          env:
            # Pod ordinal → shard index (Kubernetes 1.28+ exposes the pod index label).
            - name: INSTANCE_INDEX
              valueFrom:
                fieldRef:
                  fieldPath: metadata.labels['apps.kubernetes.io/pod-index']
            - name: INSTANCE_COUNT
              value: "${n}"
            - name: POD_NAME
              valueFrom:
                fieldRef:
                  fieldPath: metadata.name
${secretEnv ? secretEnv + '\n' : ''}          readinessProbe:
            httpGet:
              path: /v1/health
              port: api
            initialDelaySeconds: 3
            periodSeconds: 10
          livenessProbe:
            httpGet:
              path: /v1/health
              port: api
            initialDelaySeconds: 10
            periodSeconds: 20
          resources:
            requests:
              cpu: "500m"
              memory: "512Mi"
            limits:
              cpu: "2"
              memory: "1Gi"
---
apiVersion: v1
kind: Service
metadata:
  name: ${name}
  labels:
    app.kubernetes.io/name: ${name}
spec:
  clusterIP: None
  selector:
    app.kubernetes.io/name: ${name}
  ports:
    - name: api
      port: 9080
      targetPort: api
${secretManifest}`;
}

export function deployReadme(
  pipelineName: string,
  replicas: number,
  image: string,
  envVars: Array<{ name: string; value: string }> = [],
): string {
  const name = slug(pipelineName) || 'data-pipeline';
  const secretsSection = envVars.length
    ? `
## Secrets / connection credentials

This pipeline binds one or more connections. Their non-secret fields are inlined
into \`*.deploy.datapipeline\`; **secret values are referenced as \`\${ENV_VAR}\`**
and must be supplied at runtime. The engine expands \`\${VAR}\` in config values
from the environment.

Required variables:

${envVars.map((e) => `- \`${e.name}\``).join('\n')}

A filled-in \`*.deploy.datapipeline.env.example\` (with real values) was generated
next to the pipeline — **do not commit it**. For Kubernetes, edit the
\`${name}-secrets\` Secret in \`k8s-statefulset.yaml\` (the pods read these via
\`secretKeyRef\`). For local/Docker:

\`\`\`sh
docker run --env-file ${name}.env ${image}
\`\`\`
`
    : '';
  return `# Deploying ${name}

Generated by Flogo Data Pipeline Studio.

## Build the image

\`\`\`sh
docker build -t ${image} -f Dockerfile .
docker push ${image}
\`\`\`

## Deploy to Kubernetes (${replicas} sharded replicas)

\`\`\`sh
kubectl apply -f k8s-statefulset.yaml
kubectl rollout status statefulset/${name}
\`\`\`

Each pod receives \`INSTANCE_INDEX\` (its ordinal) and \`INSTANCE_COUNT=${replicas}\`.
The engine uses these to deterministically shard source partitions across pods —
no coordinator or shared state required.

Health/liveness are served at \`GET /v1/health\` on port 9080.
${secretsSection}`;
}
